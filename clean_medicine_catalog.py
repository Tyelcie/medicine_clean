def clean_text(value):
    if pd.isna(value):
        return ""
    value = unicodedata.normalize("NFKC", str(value))
    value = value.replace("\u00a0", " ").replace("\u3000", " ")
    value = re.sub(r"\s+", "", value)
    return value.strip()


def clean_spec(value):
    value = clean_text(value)
    if not value:
        return ""
    value = value.replace("＊", "*").replace("×", "*").replace("x", "*").replace("X", "*")
    value = value.replace("，", ",").replace("、", "+")
    value = value.replace("／", "/").replace("：", ":")
    value = value.replace("克", "g").replace("毫克", "mg").replace("微克", "ug")
    value = value.replace(",", ".")
    value = re.sub(r"\*+", "*", value)
    value = re.sub(r"/{2,}", "/", value)
    value = re.sub(r":{2,}", ":", value)
    value = re.sub(r"(mg|ug|g|ml|IU|单位)\s*\*\s*", r"\1*", value, flags=re.I)
    value = re.sub(r"\s+", "", value)
    # 统一常见单位书写，保留剂型和包装数量信息。
    value = re.sub(r"(?i)iu", "IU", value)
    value = re.sub(r"(?i)单位", "单位", value)
    return value.strip("/*:，;； ")


def normalize_mass_spec(value):
    """将单一质量含量统一为mg，便于识别g与mg等价规格。"""
    match = re.fullmatch(r"(\d+(?:\.\d+)?)(mg|g)/(片|粒|袋|支|瓶|丸)", value, flags=re.I)
    if not match:
        return value
    amount, unit, form = match.groups()
    amount = float(amount)
    if unit.lower() == "g":
        amount *= 1000
    normalized = f"{amount:g}mg/{form}"
    return normalized


def normalize_combo_spec(value):
    """统一复方片剂规格中成分分隔符和成分顺序以外的格式差异。"""
    value = value.replace("（", "(").replace("）", ")")
    value = re.sub(r"\((\d+(?:\.\d+)?mg)\+(\d+(?:\.\d+)?mg)\)/片", r"\1+\2/片", value)
    value = re.sub(r"(\d+(?:\.\d+)?mg)/(\d+(?:\.\d+)?mg)(?:/片)?", r"\1+\2/片", value)
    value = value.replace("mg/片", "mg/片")
    return value


